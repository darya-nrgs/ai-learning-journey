import os
from openai import OpenAI
from dotenv import load_dotenv

load_dotenv()

class CodeAgent:
    """Agent ساده برای نوشتن کد Python"""
    
    def __init__(self):
        self.client = OpenAI(
            api_key=os.getenv("NINE_ROUTER_API_KEY"),
            base_url="http://localhost:20128/v1"
        )
        self.model = "kr/claude-sonnet-4.5"
    
    def generate_code(self, description):
        """تولید کد بر اساس توضیح"""
        
        print(f"\n🤖 در حال نوشتن کد برای: {description}")
        print("-" * 60)
        
        response = self.client.chat.completions.create(
            model=self.model,
            messages=[
                {
                    "role": "system",
                    "content": """تو یک برنامه‌نویس Python حرفه‌ای هستی.
کد تمیز و خوانا بنویس با:
- Docstrings
- Type hints
- Comments برای قسمت‌های پیچیده
- کد تست‌پذیر"""
                },
                {
                    "role": "user",
                    "content": f"بنویس: {description}"
                }
            ],
            temperature=0.3
        )
        
        return response.choices[0].message.content

def main():
    print("=" * 60)
    print("🤖 اولین AI Agent من (با 9router)")
    print("=" * 60)
    
    agent = CodeAgent()
    
    # چند مثال
    examples = [
        "تابع برای حساب فاکتوریل",
        "تابع برای چک کردن عدد اول",
        "تابع برای محاسبه فیبوناچی"
    ]
    
    print("\n📋 مثال‌ها:")
    for i, ex in enumerate(examples, 1):
        print(f"   {i}. {ex}")
    
    choice = input("\nانتخاب کن (1-3) یا توضیح خودت رو بنویس: ")
    
    if choice.isdigit() and 1 <= int(choice) <= 3:
        request = examples[int(choice) - 1]
    else:
        request = choice
    
    # تولید کد
    code = agent.generate_code(request)
    
    print("\n✅ کد تولید شد:")
    print("=" * 60)
    print(code)
    print("=" * 60)
    
    # ذخیره
    filename = "generated_code.py"
    with open(filename, "w", encoding="utf-8") as f:
        f.write(f"# Generated by AI Agent\n")
        f.write(f"# Request: {request}\n\n")
        f.write(code)
    
    print(f"\n💾 ذخیره شد در: {filename}")

if __name__ == "__main__":
    main()
